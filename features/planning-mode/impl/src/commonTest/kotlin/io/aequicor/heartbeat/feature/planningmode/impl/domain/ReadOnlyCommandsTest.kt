    }

    @Test
    fun `power shell commands are never classified`() {
        assertFalse(isReadOnlyCommand("Get-ChildItem", ShellKind.PowerShell))
        assertFalse(isReadOnlyCommand("ls", ShellKind.PowerShell))
    }

    @Test
    fun `very long commands need a decision`() {
        assertFalse(isReadOnlyCommand("echo " + "a".repeat(5_000)))
    }
