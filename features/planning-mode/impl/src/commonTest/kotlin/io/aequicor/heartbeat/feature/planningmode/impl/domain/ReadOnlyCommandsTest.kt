    @Test
    fun `reading commands are read-only`() {
        readOnly.forEach { assertTrue(isReadOnlyCommand(it), it) }
    }

    @Test
    fun `commands that may change anything need a decision`() {
        needsDecision.forEach { assertFalse(isReadOnlyCommand(it), it) }
    }

    @Test
    fun `syntax the shell could expand needs a decision`() {
        listOf(
            "wc -l *.kt",
            "ls file?",
            "ls [ab].kt",
            "ls a]",
            "ls ~",
            "cat ~/notes",
            "git show HEAD~1",
            "echo {a,b}",
            "echo a}",
            "echo \$HOME",
            "echo \${HOME}",
            "echo \"\$HOME\"",
            "echo \"\\\$HOME\"",
            "echo \$'\\x41'",
            "echo !!",
            "ls a(b)",
            "ls a)",
            "cat < ~/secret",
            "cat < *.txt",
            "ls \\\nrm",
            "echo \"a\\\nb\"",
        ).forEach { assertFalse(isReadOnlyCommand(it), it) }
    }

