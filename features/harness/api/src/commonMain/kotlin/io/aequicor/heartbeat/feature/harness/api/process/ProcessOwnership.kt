package io.aequicor.heartbeat.feature.harness.api.process

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlin.jvm.JvmInline

/**
 * Stable shared work identity, identical on every host. The host hashes the canonical external task identity;
 * a local profile id, process incarnation or PR description is not a shared identity. Never delete and reuse a
 * coordinator entry: its monotonically growing epoch fences every earlier lifetime of that work.
 */
@Serializable
@JvmInline
public value class OwnershipKey(public val value: String) {
    init {
        require(Regex("[0-9a-f]{64}").matches(value)) { "Invalid ownership key" }
    }

    override fun toString(): String = "OwnershipKey(***)"
}

/** Opaque installation/profile identity generated and persisted by the trusted host, never supplied by scripts. */
@Serializable
@JvmInline
public value class ExecutorHostId(public val value: String) {
    init {
        require(Regex("[0-9a-f]{32}").matches(value)) { "Invalid executor host" }
    }

    override fun toString(): String = "ExecutorHostId(***)"
}

/** A capability correlation, not a credential: the coordinator must authenticate the caller independently. */
@Serializable
public data class OwnershipFence(val key: OwnershipKey, val host: ExecutorHostId, val epoch: Long) {
    init {
        require(epoch > 0) { "Invalid ownership epoch" }
    }

    override fun toString(): String = "OwnershipFence(epoch=$epoch, ***)"
}

/** Persisted transfer phases; no elapsed time or lease expiration advances any of them. */
@Serializable
public enum class OwnershipPhase {
    /** The owner may admit new work through a host fence. */
    @SerialName("active")
    Active,

    /** New admissions are closed before stopping the old owner's executors. */
    @SerialName("preparing")
    Preparing,

    /** Stop or wait for every admitted executor and external call; unknown outcomes stay blocked. */
    @SerialName("quiescing")
    Quiescing,

    /** Executors and calls are drained and a portable checkpoint is durable; only the named target may claim. */
    @SerialName("exported")
    Exported,

    /** The next owner is fenced in but cannot mutate until external facts and checkpoint are reconciled. */
    @SerialName("reconciling")
    Reconciling,
}

/**
 * Content-addressed portable checkpoint, not the data itself. The host exports an allowlisted process manifest
 * and sealed evidence separately; it excludes credentials, native session handles, local paths and arbitrary
 * ScriptData. [digest] is the SHA-256 of those immutable bytes, [reference] an opaque locator in the transport.
 * Neither this pointer nor a sealed result proves that an external operation succeeded.
 */
@Serializable
public data class OwnershipCheckpoint(val digest: String, val reference: String) {
    init {
        require(Regex("[0-9a-f]{64}").matches(digest)) { "Invalid checkpoint digest" }
        require(isPlainToken(reference)) { "Invalid checkpoint reference" }
    }

    override fun toString(): String = "OwnershipCheckpoint(***)"
}

/**
 * Durable immutable intent. [id] is generated by the host, globally unique and never reused; [source] is retained
 * after claim so an interrupted sender or recipient can identify the same transfer without starting another one.
 */
@Serializable
public data class OwnershipTransfer(
    val id: String,
    val source: OwnershipFence,
    val target: ExecutorHostId,
    val checkpoint: OwnershipCheckpoint? = null,
) {
    init {
        require(Regex("[0-9a-f]{32}").matches(id)) { "Invalid transfer identity" }
        require(source.host != target) { "Transfer target is the current owner" }
    }

    override fun toString(): String = "OwnershipTransfer(***)"
}

/**
 * Shared coordinator value, separate from the local [ProcessRecord]. Only an authenticated, linearizable
 * compare-and-set may persist [reduceOwnership]; a profile CAS, GitHub comment or label cannot implement it.
 * [revision] increases on every change including cancellation. [fence] changes on claim and cancellation, so a
 * delayed operation admitted before Prepare cannot become current again when a transfer is cancelled.
 *
 * This value describes cooperative fencing only. A native process or remote API that does not validate epochs
 * cannot be revoked by a read-before-write check. Export requires confirmed termination of all native executors
 * and drainage of all admitted calls. Network loss, expiry and missing status are never termination receipts.
 * [permits] share this same CAS value: Prepare closes new admissions but cannot lose an admitted action.
 * Export and activation require the ledger to be empty; unknown outcomes never expire. [nextPermit] never resets.
 * Old clients must be denied access to coordinated work by the host; deserializing this record is not that gate.
 */
@Serializable
public data class ProcessOwnership(
    val fence: OwnershipFence,
    val revision: Long = 1,
    val phase: OwnershipPhase = OwnershipPhase.Active,
    val transfer: OwnershipTransfer? = null,
    val permits: List<OwnershipPermit> = emptyList(),
    val nextPermit: Long = 1,
) {
    init {
        require(revision > 0 && nextPermit > 0) { "Invalid ownership revision" }
        require(permits.size <= MAX_OWNERSHIP_PERMITS) { "Too many ownership permits" }
        require(permits.map { it.id }.distinct().size == permits.size) { "Duplicate permit identity" }
        require(permits.map { it.sequence }.distinct().size == permits.size) { "Duplicate permit sequence" }
        require(permits.all { it.sequence < nextPermit && it.fence.key == fence.key }) { "Invalid permit fence" }
        require(phase != OwnershipPhase.Exported || permits.isEmpty()) { "Export has live permits" }
        require(phase != OwnershipPhase.Active || permits.all { it.fence == fence }) { "Active permit is stale" }
        val pending = transfer
        require(phase == OwnershipPhase.Active || pending != null) { "Missing transfer" }
        if (pending != null) {
            require(pending.source.key == fence.key) { "Transfer belongs to different work" }
            when (phase) {
                OwnershipPhase.Preparing, OwnershipPhase.Quiescing, OwnershipPhase.Exported ->
                    require(fence == pending.source) { "Transfer source is not current" }

                OwnershipPhase.Reconciling, OwnershipPhase.Active -> {
                    require(pending.source.epoch < Long.MAX_VALUE && fence.epoch == pending.source.epoch + 1) {
                        "Invalid transfer epoch"
                    }
                    require(fence.host == pending.source.host || fence.host == pending.target) {
                        "Invalid transfer owner"
                    }
                    require(fence.host != pending.target || pending.checkpoint != null) {
                        "Missing recipient checkpoint"
                    }
                }
            }
        }
        require(phase != OwnershipPhase.Exported || pending?.checkpoint != null) { "Missing checkpoint" }
    }

    /** Local hint only: authoritative admission also needs an online coordinator permit held through the call. */
    public fun accepts(expected: OwnershipFence): Boolean = phase == OwnershipPhase.Active && expected == fence

    override fun toString(): String = "ProcessOwnership(revision=$revision, phase=$phase, ***)"
}
